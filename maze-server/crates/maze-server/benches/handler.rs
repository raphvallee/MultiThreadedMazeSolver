fn bench_handler(c: &mut Criterion) {
    let start = parts("/", None);
    let bonk = parts("/move", Some("dWU=".to_string())); // "ue": bonks on u
    let well = parts("/move", Some("cnI=".to_string())); // "rr": going well
    let solved = parts("/move", Some(solution_cookie()));
    let lost = parts("/reset", None);

    c.bench_function("route/start_page", |b| {
        b.iter(|| route_parts(black_box(&start)))
    });
    c.bench_function("route/bonk_spec_pure", |b| {
        b.iter(|| route_parts(black_box(&bonk)))
    });
    c.bench_function("route/well_spec_pure", |b| {
        b.iter(|| route_parts(black_box(&well)))
    });
    c.bench_function("route/solved_flag", |b| {
        b.iter(|| route_parts(black_box(&solved)))
    });
    c.bench_function("route/lost_404", |b| {
        b.iter(|| route_parts(black_box(&lost)))
    });
}

criterion_group!(benches, bench_handler);
criterion_main!(benches);