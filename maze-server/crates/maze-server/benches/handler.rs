fn parts(uri: &'static str, cookie: Option<String>) -> hyper::http::request::Parts {
    let mut b = hyper::Request::builder().method("GET").uri(uri);
    if let Some(c) = cookie {
        b = b.header("cookie", format!("path={c}"));
    }
    b.body(()).unwrap().into_parts().0
}

